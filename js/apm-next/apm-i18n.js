    function normaliseLang(l) {
        var s = String(l || '').toLowerCase().slice(0, 2);
        return s === 'ro' ? 'ro' : 'en';
    }

    /** Translate a key; {name} placeholders are filled from vars. Missing keys fall back to English, then to the key. */
    function t(key, lang, vars) {
        var dict = STRINGS[normaliseLang(lang)] || STRINGS.en;
        var s = dict[key];
        if (s == null) s = STRINGS.en[key];
        if (s == null) s = key;
        if (vars) s = s.replace(/\{(\w+)\}/g, function (m, k) { return vars[k] != null ? String(vars[k]) : m; });
        return s;
    }

    return { STRINGS: STRINGS, t: t, normaliseLang: normaliseLang };
